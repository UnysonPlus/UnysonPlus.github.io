#!/usr/bin/env node
/**
 * gen-kit-tools.mjs — regenerate the AI Dev Kit "Tools" reference page from the kit's own tool inventory.
 *
 * The kit's `tools/README.md` is the single source of truth for the runnable tooling (the "I need to… →
 * run this" table). This script reads it and emits:
 *
 *   ai-dev-kit/tools.md   — the public Tools reference (frontmatter + the kit's inventory, de-linked)
 *
 * The .md is GENERATED — never hand-edit it. Add/rename a tool in the kit's tools/README.md, then re-run:
 *     node scripts/gen-kit-tools.mjs
 *
 * The kit lives OUTSIDE this repo (both under d:\Web Dev\). Resolution order:
 *   1. env KIT_DIR
 *   2. ../../UnysonPlus-AI-Dev-Kit   (relative to this repo)
 *   3. d:/Web Dev/UnysonPlus-AI-Dev-Kit
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, '..');

function findKit() {
  const cands = [process.env.KIT_DIR, resolve(REPO, '..', '..', 'UnysonPlus-AI-Dev-Kit'), 'd:/Web Dev/UnysonPlus-AI-Dev-Kit'];
  for (const c of cands) { if (c && existsSync(join(c, 'tools', 'README.md'))) return c; }
  console.error('gen-kit-tools: could not find the kit (tools/README.md). Set KIT_DIR=<path-to-UnysonPlus-AI-Dev-Kit>.');
  process.exit(1);
}

const KIT = findKit();
let src = readFileSync(join(KIT, 'tools', 'README.md'), 'utf8');

// Drop the kit's own H1 (the page title comes from frontmatter — avoid a double H1). Tolerate any
// leading whitespace/BOM before the heading.
src = src.replace(/^﻿?\s*#\s+.*\r?\n/, '');
// De-link relative markdown links that don't resolve on the docs site: [text](something.md#..) -> text.
// Absolute http(s) links are kept.
src = src.replace(/\[([^\]]+)\]\((?!https?:)[^)]+\)/g, '$1');
// Tidy leading/trailing whitespace.
src = src.trim() + '\n';

const front = `---
title: Tools
sidebar_label: Tools
sidebar_position: 7
slug: /tools
description: The AI Dev Kit's runnable tools — the verification/measure suite (probe, shot, measure, fidelity-check, container-check, compare, props, section-audit), the capture pipeline, and the page-composer. When to reach for each.
---

{/* GENERATED by scripts/gen-kit-tools.mjs from the kit's tools/README.md — do not hand-edit. */}

The kit ships a set of **runnable tools** so an agent never hand-rolls a Playwright probe or guesses a
measurement. The inventory below is generated from the kit's own \`tools/README.md\` — the same file the
agent reads inside the repo — so this page and the kit stay in lockstep. Each JS tool folder is
self-contained (its own \`package.json\` → its own Playwright + image deps via one \`npm install\`).

`;

const out = front + src;
const dest = join(REPO, 'ai-dev-kit', 'tools.md');
writeFileSync(dest, out, 'utf8');
console.log('wrote', dest, `(${out.length} bytes) from`, join(KIT, 'tools', 'README.md'));
